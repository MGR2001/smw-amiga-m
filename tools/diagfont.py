def glyph_bytes(ch):
    """8 bytes: filas 0-6 de la letra (columnas 1-5 de la celda) y la 7 vacia"""
    rows = G.get(ch, G[" "])
    out = []
    for r in rows:
        b = 0
        for i, c in enumerate(r):
            if c == "#":
                b |= 0x40 >> i
        out.append(b)
    return out + [0]


def table():
    """{caracter: 8 bytes} de todos los que tienen letra"""
    return {ch: glyph_bytes(ch) for ch in G}


def main():
    for ch, rows in G.items():
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    seen = {}
    for ch in G:
        k = tuple(glyph_bytes(ch))
        assert k not in seen or ch == " ", "letras iguales: %r %r" % (ch, seen.get(k))
        seen[k] = ch
    lines = ["; diagfont.i - GENERADO por tools/diagfont.py (no editar a mano).",
             "; Letra 5x7 en celdas de 8x8 del espacio ($20) a la Z ($5A), 8 bytes",
             "; por caracter, bit 7 = pixel de la izquierda.",
             "DFONT_FIRST equ %d" % FIRST,
             "DFONT_LAST  equ %d" % LAST,
             "diagfont:"]
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        lines.append("        dc.b    " + ",".join("$%02x" % b for b in glyph_bytes(ch))
                     + "   ; %s" % (repr(ch) if ch in G else "(vacio)"))
    open(OUT, "w", encoding="ascii", newline="\n").write("\n".join(lines) + "\n")
    print("-> %s (%d caracteres)" % (os.path.relpath(OUT), LAST - FIRST + 1))


if __name__ == "__main__":
    main()
